#!/usr/bin/env python3
"""Write docs/COVERAGE.md from the built data packs: what each vehicle line offers.
Usage: python3 -I tools/coverage.py [data dir]        (English packs; falls back to the German ones)"""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from platforms import PLATFORMS
import jobs as jobdefs

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    data = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "data")
    rows = []; jobs = {}; titles = {j["id"]: j["title"] for j in jobdefs.JOBS}
    for p in PLATFORMS:
        f = os.path.join(data, p["id"] + ".json")
        if not os.path.exists(f): f = os.path.join(data, p["id"] + "_de.json")
        if not os.path.exists(f): continue
        d = json.load(open(f, encoding="utf-8")); mods = d["mods"]
        cat = lambda c: sum(1 for m in mods for s in m["svc"] if s[1] == c)
        rows.append((p["id"], p["title"], len(mods), sum(1 for m in mods if m["ids"] and m.get("link") != 1),
                     sum(1 for m in mods if m.get("link") == 1), sum(1 for m in mods if not m["ids"]),
                     sum(len(m["svc"]) for m in mods), cat("L"), cat("A"), cat("R"), cat("C") + cat("W"),
                     sum(len(m["dtc"]) for m in mods), sum(1 for m in mods if any(s[1] == "E" for s in m["svc"])),
                     sum(1 for m in mods if m.get("sk")), sum(1 for m in mods if m.get("sfd")), len(d.get("jobs", [])),
                     ", ".join(d.get("vin", [])) or "-"))
        jobs[p["id"]] = {j["id"] for j in d.get("jobs", [])}
    o = ["# Vehicle coverage", "",
         "Generated by `tools/coverage.py` from the data packs. Numbers are what the diagnostic database of each line",
         "defines; whether a given car has a control unit fitted shows in the scan.", "",
         "| Line | Vehicle | VIN types | Control units | on CAN | on K-line | sub-bus only | Functions | Live data | Actuator tests | Routines | Coding / adaptation | Fault codes | Units with fault environment data | Units with a mapped coding key | Units with SFD | Guided jobs |",
         "|---|---|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"]
    for r in rows:
        o.append("| %s | %s | %s | %d | %d | %d | %d | %d | %d | %d | %d | %d | %d | %d | %d | %d | %d |" % (
            r[0], r[1], r[16], r[2], r[3], r[4], r[5], r[6], r[7], r[8], r[9], r[10], r[11], r[12], r[13], r[14], r[15]))
    ids = [r[0] for r in rows]
    o += ["", "*sub-bus only*: units behind another control unit (VW TP 1.6 / TP 2.0 transport), listed in the scan report but",
          "not reachable through an ISO-TP or K-line adapter.", "", "## Guided jobs per line", "",
          "| Job | " + " | ".join(ids) + " |", "|---|" + ":-:|" * len(ids)]
    for j in jobdefs.JOBS:
        o.append("| %s | %s |" % (titles[j["id"]], " | ".join("yes" if j["id"] in jobs.get(i, ()) else "" for i in ids)))
    o += ["", "A job appears for a line only when the function it needs was found in that line's database with a known",
          "identifier. Everything else stays available as an individual function under *Open module*.", ""]
    out = os.path.join(here, "..", "docs", "COVERAGE.md")
    open(out, "w", encoding="utf-8").write("\n".join(o))
    print("\n".join(o))

if __name__ == "__main__":
    main()
